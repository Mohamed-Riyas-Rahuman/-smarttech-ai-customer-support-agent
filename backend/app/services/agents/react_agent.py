"""LangChain ReAct Agent for SmartTech Customer Support.

Uses the installed LangChain agent architecture (`create_agent`) with tool calling,
grounding in retrieved knowledge base documentation, the shared Groq LLM client,
and Langfuse observability tracing.
"""

from typing import Any
from langchain.agents import create_agent
from langchain_core.messages import HumanMessage, SystemMessage
from pydantic import BaseModel, Field

from app.core.logging import logger
from app.services.agents.langchain_tools import ToolExecutionContext, create_agent_tools
from app.integrations.llm.llm_service import get_llm


class AgentSupportDraft(BaseModel):
    """Structured response schema generated by the LangChain ReAct agent."""

    draft_body: str = Field(
        ...,
        description="The evidence-based, professional customer support email draft.",
    )
    confidence_score: float = Field(
        default=0.90,
        description="Confidence score between 0.0 and 1.0.",
    )
    reasoning_summary: str = Field(
        ...,
        description="Brief summary of reasoning and retrieved evidence.",
    )
    category: str = Field(
        default="general",
        description="Classification category: order, warranty, technical, returns, billing, general.",
    )
    priority: str = Field(
        default="medium",
        description="Priority recommendation: low, medium, high, urgent.",
    )
    escalation_recommended: bool = Field(
        default=False,
        description="True if human supervisor intervention is required (e.g. lost shipment, expired warranty exception).",
    )


def get_groq_langchain_chat():
    """Return the same configured Groq model used by RAG and quality workflows."""
    return get_llm(temperature=0.2, max_tokens=700)


def run_react_agent_for_ticket(
    context: ToolExecutionContext,
    subject: str,
    latest_message: str,
    thread_context: str = "",
    planning_intent: str = "general_support",
) -> AgentSupportDraft:
    """Execute LangChain ReAct agent with dynamic tool calling and Langfuse tracing."""
    tools = create_agent_tools(context)
    llm = get_groq_langchain_chat()

    system_prompt = (
        "You are the SmartTech AI Support Agent. Your task is to analyze the customer's "
        "support ticket, dynamically call appropriate tools to gather verified evidence, "
        "and generate a strictly evidence-based, professional, and empathetic email response draft.\n\n"
        "AVAILABLE TOOLS:\n"
        "- get_customer_details: Retrieve verified customer profile details.\n"
        "- get_registered_devices: Retrieve all hardware registered to the customer.\n"
        "- get_customer_orders: Retrieve order history with order numbers, carriers, and tracking.\n"
        "- get_device_by_serial: Look up a specific device by serial number (customer ownership enforced).\n"
        "- get_warranty_details: Look up warranty policy status, expiration date, and coverage for a serial number.\n"
        "- get_product_specifications: Look up public specs from catalog by SKU or product name.\n"
        "- search_knowledge_base: Search official documentation, user guides, and troubleshooting steps.\n\n"
        "STRICT RULES:\n"
        "1. Dynamic tool usage: Call search_knowledge_base for technical troubleshooting or FAQ questions. "
        "Call get_customer_orders for order inquiries. Call get_warranty_details or get_registered_devices for device/warranty questions.\n"
        "2. Grounding: Only state facts verified through tools or approved documentation. Never invent order numbers, tracking carriers, serial numbers, or troubleshooting steps.\n"
        "3. Order Inquiries: You MUST state the exact order number (e.g. ORD-...), shipping carrier, tracking number, and delivery status.\n"
        "4. Troubleshooting: Cite the document title and provide clear step-by-step instructions from approved knowledge base results.\n"
        "5. Expired Warranty: If a device warranty is expired or not active, DO NOT promise free repair or replacement. "
        "State clearly that the manufacturer warranty has expired and offer troubleshooting or out-of-warranty repair options.\n"
        "6. Escalation: If package is lost/missing or customer demands free replacement on an expired device, mark escalation_recommended=true.\n"
        "7. Customer Privacy: Never disclose information about other customers.\n"
        "8. Output structured response matching the schema."
    )

    agent_graph = create_agent(
        model=llm,
        tools=tools,
        system_prompt=system_prompt,
        response_format=AgentSupportDraft,
    )

    user_prompt = (
        f"Support Ticket Subject: {subject}\n"
        f"Customer Message: {latest_message}\n"
        f"Conversation History: {thread_context or 'None'}\n"
        f"Initial Intent: {planning_intent}\n"
        "Analyze this request, use necessary tools to look up records or documentation, and provide the final structured response."
    )

    callbacks = []
    if context.tracer and context.execution_id is not None:
        cb = context.tracer.get_langchain_callback(context.execution_id)
        if cb:
            callbacks.append(cb)

    config: dict[str, Any] = {}
    if callbacks:
        config["callbacks"] = callbacks

    logger.info("Executing LangChain ReAct agent for ticket %s", context.ticket.ticket_number)
    result = agent_graph.invoke(
        {"messages": [HumanMessage(content=user_prompt)]},
        config=config if config else None,
    )

    structured = result.get("structured_response")
    if isinstance(structured, AgentSupportDraft):
        return structured
    elif isinstance(structured, dict):
        return AgentSupportDraft(**structured)
    else:
        # Fallback if model returned standard text message
        last_msg = result["messages"][-1]
        raw_content = getattr(last_msg, "content", "")
        return AgentSupportDraft(
            draft_body=raw_content,
            confidence_score=0.85,
            reasoning_summary="Generated response via LangChain ReAct tool calling.",
            category="general",
            priority="medium",
            escalation_recommended=False,
        )
